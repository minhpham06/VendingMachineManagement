package model;

import java.io.Serializable;
import java.sql.Timestamp;

public class VendAlert implements Serializable {
    private static final long serialVersionUID = 1L;

    private int alertId;
    private Integer sessionId;
    private Integer slotId;
    private String slotCode;
    private String ruleCode;
    private String severity;
    private String message;
    private String status; // 'OPEN', 'RESOLVED'
    private Integer handledBy;
    private String handlerName;
    private String handledNote;
    private Timestamp createdAt;

    public VendAlert() {
    }

    public int getAlertId() {
        return alertId;
    }

    public void setAlertId(int alertId) {
        this.alertId = alertId;
    }

    public Integer getSessionId() {
        return sessionId;
    }

    public void setSessionId(Integer sessionId) {
        this.sessionId = sessionId;
    }

    public Integer getSlotId() {
        return slotId;
    }

    public void setSlotId(Integer slotId) {
        this.slotId = slotId;
    }

    public String getSlotCode() {
        return slotCode;
    }

    public void setSlotCode(String slotCode) {
        this.slotCode = slotCode;
    }

    public String getRuleCode() {
        return ruleCode;
    }

    public void setRuleCode(String ruleCode) {
        this.ruleCode = ruleCode;
    }

    public String getSeverity() {
        return severity;
    }

    public void setSeverity(String severity) {
        this.severity = severity;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Integer getHandledBy() {
        return handledBy;
    }

    public void setHandledBy(Integer handledBy) {
        this.handledBy = handledBy;
    }

    public String getHandlerName() {
        return handlerName;
    }

    public void setHandlerName(String handlerName) {
        this.handlerName = handlerName;
    }

    public String getHandledNote() {
        return handledNote;
    }

    public void setHandledNote(String handledNote) {
        this.handledNote = handledNote;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    public boolean isResolved() {
        return "RESOLVED".equalsIgnoreCase(status);
    }
}
